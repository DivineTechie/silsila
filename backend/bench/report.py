"""Write docs/evidence/README.md from the benchmark JSON files (no numbers are
typed by hand: every figure in the report is read from a results file)."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import yaml

from silsila import params
from silsila.sim.sources import CITATIONS, assumptions_doc

from .common import EVIDENCE


def _load(name: str) -> dict[str, Any] | None:
    p = EVIDENCE / name
    return json.loads(p.read_text()) if p.exists() else None


def pct(x, d=1):
    return "n/a" if x is None else f"{100 * x:.{d}f}%"


def ci(c, f=pct):
    return "n/a" if not c or c[0] is None else f"{f(c[0])} to {f(c[1])}"


def num(x, d=1):
    return "n/a" if x is None else f"{x:.{d}f}"


def write_readme() -> Path:
    b1, b2, b3, b4, b5, pf = (_load(n) for n in ("b1_engine.json", "b2_robustness.json", "b3_nejm.json", "b4_uae.json",
                                                   "b5_sensitivity.json", "perf_engine.json"))
    ra = _load("run_all.json")
    L: list[str] = []
    w = L.append
    w("# Silsila evidence: engine correctness, robustness and synthetic-family benchmarks\n")
    w("**All families in this folder are SYNTHETIC.** They are generated by `backend/src/silsila/sim` from published population "
      "numbers plus labelled assumptions. No real person's data is used. Results describe the model, not observed patients.\n")
    if ra:
        p = ra["provenance"]
        w(f"Generated {p['generated_utc']} from commit `{p['git_commit']}`{' (uncommitted changes present)' if p['working_tree_dirty'] else ''}, "
          f"Python {p['python']}, numpy {p['numpy']}, scipy {p['scipy']}, {p['workers']} worker processes, "
          f"{'QUICK (reduced sample sizes)' if p['quick'] else 'full'} run, total {ra['total_seconds']:.0f} s.\n")
    w("## Reproduce\n")
