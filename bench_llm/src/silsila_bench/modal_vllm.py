"""Serve one Hugging Face model with vLLM on Modal (OpenAI-compatible, tool calling enabled).

Deploy one app per model (the model is chosen with an environment variable at deploy time):

    cd bench_llm
    SILSILA_BENCH_MODEL=jais-3-7b uv run modal deploy src/silsila_bench/modal_vllm.py

The URL printed by Modal (https://<workspace>--silsila-vllm-<model>-serve.modal.run) is the base URL;
put it in .env as MODAL_URL_JAIS_3_7B=<url> (or set MODAL_WORKSPACE). Requests need the bearer key in
SILSILA_VLLM_API_KEY (generated by you, stored in .env and sent to Modal as a secret). Containers scale
to zero after SCALEDOWN seconds idle, so stop paying by simply not sending requests, or run
`uv run modal app stop silsila-vllm-<model>`.

Serving flags per model come from the model cards (see models.py docstring). This file is
self-contained: Modal imports it inside the container without the rest of the package.
"""

from __future__ import annotations

import os
import subprocess
import threading

import modal

VLLM_VERSION = "0.33.0"     # Jais 3 needs vllm >= 0.30 for the k2_horizon parsers
PORT = 8000
SCALEDOWN = 15 * 60
MINUTES = 60

SERVE: dict[str, dict] = {
    "jais-3-7b": {
        "repo": "inception42/Jais-3-7B", "gpu": "H100",
        "args": ["--trust-remote-code", "--dtype", "bfloat16", "--reasoning-parser", "k2_horizon",
                 "--enable-auto-tool-choice", "--tool-call-parser", "k2_horizon", "--max-model-len", "65536"],
    },
    "jais-3-32b": {
        "repo": "IFM/Jais-3-32B-FP8", "gpu": "H100",
        "args": ["--trust-remote-code", "--model-impl", "vllm", "--reasoning-parser", "k2_horizon",
                 "--enable-auto-tool-choice", "--tool-call-parser", "k2_horizon", "--max-model-len", "49152",
                 "--gpu-memory-utilization", "0.92"],
    },
    "k2-think-v2": {
        # 72.5B parameters: 145 GB in BF16. FP8 quantisation on load fits 2 x H100 80GB with KV cache room.
        "repo": "IFM/K2-Think-V2", "gpu": "H100:2",
        "args": ["--tensor-parallel-size", "2", "--quantization", "fp8", "--reasoning-parser", "deepseek_r1",
                 "--enable-auto-tool-choice", "--tool-call-parser", "hermes", "--max-model-len", "49152",
                 "--gpu-memory-utilization", "0.92"],
    },
    "bimedix2-8b": {
        # LLaVA wrapper around Llama 3.1 8B; text-only prompts. Llama 3.1 chat template has JSON tool calls.
        "repo": "MBZUAI/BiMediX2-8B-hf", "gpu": "H100",
        "args": ["--trust-remote-code", "--max-model-len", "32000", "--enable-auto-tool-choice",
                 "--tool-call-parser", "llama3_json", "--limit-mm-per-prompt", '{"image": 0}'],
    },
    "llama3-med42-8b": {
        # Chat template has no tool support: tools are described in the prompt by the client.
        "repo": "m42-health/Llama3-Med42-8B", "gpu": "H100",
        "args": ["--max-model-len", "8192"],
    },
}

MODEL = os.environ.get("SILSILA_BENCH_MODEL", "jais-3-7b")
if MODEL not in SERVE:
    raise RuntimeError(f"SILSILA_BENCH_MODEL must be one of {sorted(SERVE)}")
CFG = SERVE[MODEL]

image = (
    modal.Image.debian_slim(python_version="3.12")
    .uv_pip_install(f"vllm=={VLLM_VERSION}", "huggingface_hub[hf_transfer]")
    .env({"HF_HUB_ENABLE_HF_TRANSFER": "1", "SILSILA_BENCH_MODEL": MODEL, "VLLM_USE_V1": "1",
          # FlashInfer's top-k sampler compiles a kernel at startup and needs nvcc, which this image
          # lacks; vLLM's own sampler gives the same tokens at temperature 0.
          "VLLM_USE_FLASHINFER_SAMPLER": "0"})
)
hf_cache = modal.Volume.from_name("silsila-hf-cache", create_if_missing=True)
vllm_cache = modal.Volume.from_name("silsila-vllm-cache", create_if_missing=True)

_secret_env = {k: os.environ[k] for k in ("SILSILA_VLLM_API_KEY", "HF_TOKEN") if os.environ.get(k)}
secrets = [modal.Secret.from_dict(_secret_env)] if _secret_env else []

app = modal.App(f"silsila-vllm-{MODEL}")


@app.function(
    image=image,
    gpu=CFG["gpu"],
    volumes={"/root/.cache/huggingface": hf_cache, "/root/.cache/vllm": vllm_cache},
    secrets=secrets,
    timeout=24 * 60 * MINUTES,
    scaledown_window=SCALEDOWN,
    max_containers=1,
)
@modal.concurrent(max_inputs=128)
@modal.web_server(port=PORT, startup_timeout=40 * MINUTES)
def serve() -> None:
    n_gpu = int(CFG["gpu"].split(":")[1]) if ":" in CFG["gpu"] else 1
    cmd = ["vllm", "serve", CFG["repo"], "--served-model-name", CFG["repo"], "--host", "0.0.0.0",
           "--port", str(PORT), "--generation-config", "vllm", *CFG["args"]]
    if n_gpu > 1 and "--tensor-parallel-size" not in cmd:
        cmd += ["--tensor-parallel-size", str(n_gpu)]
    key = os.environ.get("SILSILA_VLLM_API_KEY")
    if key:
        # "--api-key=<key>" form: a key that starts with "-" would otherwise be read as a new flag.
        cmd.append(f"--api-key={key}")
    print("starting:", " ".join("--api-key=***" if c.startswith("--api-key=") else c for c in cmd), flush=True)
    proc = subprocess.Popen(cmd)

    def _exit_if_server_dies() -> None:
        # Without this, a vLLM crash leaves Modal waiting the full startup timeout on a paid GPU.
        code = proc.wait()
        print(f"vllm serve exited with code {code}; stopping the container", flush=True)
        os._exit(1)

    threading.Thread(target=_exit_if_server_dies, daemon=True).start()
